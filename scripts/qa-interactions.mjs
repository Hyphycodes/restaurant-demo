 await page.reload({waitUntil:'networkidle'});
 await expect(page.locator('[name=name]')).toHaveValue('Spicy Rigatoni — Demo Edit');
 await other.reload({waitUntil:'networkidle'});
 await expect(other.locator('[name=name]')).toHaveValue('Spicy Rigatoni');
 await page.goto(origin+'/menu',{waitUntil:'networkidle'});
 await expect(page.getByText('Spicy Rigatoni — Demo Edit',{exact:true})).toBeVisible();
 console.log('PASS admin publish -> public menu; second browser unchanged');
 await page.goto(origin+'/demo/staff',{waitUntil:'networkidle'});
