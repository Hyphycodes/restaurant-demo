 console.log('PASS order preview');
 await page.goto(origin+'/admin/menu/spicy-rigatoni',{waitUntil:'networkidle'});
 await other.goto(origin+'/admin/menu/spicy-rigatoni',{waitUntil:'networkidle'});
 await expect(other.locator('[name=name]')).toHaveValue('Spicy Rigatoni');
 await page.locator('[name=name]').fill('Spicy Rigatoni — Demo Edit');
